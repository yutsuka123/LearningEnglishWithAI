OTHER_CATEGORY = "その他"


def group_by_category(
    present: list[str], categories: dict[str, list[str]],
) -> dict[str, list[str]]:
    """DBに実在する値(present)を大分類ごとにグループ化する。対応表に無い
    値は自動的に「その他」へ（今後の新規分野追加を対応表更新忘れで隠さない
    ための安全策）。空になったグループ・「その他」自体が空なら省く。"""
    present_set = set(present)
    order_index = {v: i for i, v in enumerate(present)}
    grouped: dict[str, list[str]] = {}
    seen: set[str] = set()
    for category, items in categories.items():
        matched = [v for v in items if v in present_set]
        if matched:
            grouped[category] = matched
            seen.update(matched)
    leftover = sorted(
        (v for v in present_set - seen), key=lambda v: order_index[v],
    )
    if leftover:
        grouped[OTHER_CATEGORY] = leftover
    return grouped
